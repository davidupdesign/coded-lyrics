/**
 * Compact terminal glyph atlas — one pixel is one terminal cell.
 *
 * Every glyph is 6 rows tall with a variable width:
 *   row 0        ascender (b d f h i j k l t and digits)
 *   rows 1..4    x-height body
 *   row 5        descender (g j p q y and comma)
 *
 * `#` = ink, `.` = empty. Strokes are two cells thick so each letter is
 * packed with more of itself without growing taller.
 */

export const GLYPH_H = 6;

export type Glyph = {
  readonly width: number;
  readonly rows: readonly string[];
};

function G(...rows: string[]): Glyph {
  if (rows.length !== GLYPH_H) {
    throw new Error(`Glyph needs ${GLYPH_H} rows, got ${rows.length}`);
  }
  const width = rows[0].length;
  for (const row of rows) {
    if (row.length !== width) {
      throw new Error(`Glyph rows must all be ${width} wide, got "${row}"`);
    }
  }
  return { width, rows };
}

