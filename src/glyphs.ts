/**
 * 8×16 pixel glyph atlas for braille rendering.
 * `#` = on, `.` = off. Exactly 16 rows × 8 cols per glyph.
 */

export const PIX_W = 8;
export const PIX_H = 16;

export type Bitmap = boolean[][];

function R(...lines: string[]): Bitmap {
  if (lines.length !== PIX_H) {
    throw new Error(`Glyph needs ${PIX_H} rows, got ${lines.length}`);
  }
  return lines.map((line, i) => {
    const padded = line.padEnd(PIX_W, ".").slice(0, PIX_W);
    if (padded.length !== PIX_W) {
      throw new Error(`Row ${i} bad width`);
    }
    return [...padded].map((c) => c === "#");
  });
}

