/**
 * Half-block glyph atlases — one glyph pixel is one *sub-row*, and two sub-rows
 * are packed into a single terminal cell by `bigfont.ts` using ▀ ▄ █.
 *
 * A terminal cell is roughly 1:2 (w:h), so pairing sub-rows makes one glyph
 * pixel square on screen. Letters can therefore be drawn wide — the stretched
 * proportion a 1-pixel-per-cell atlas could never reach.
 *
 * There are two hand-drawn sizes rather than one that gets resampled.
 * Downsampling a 12-row glyph merges the rows that carry a letter's identity —
 * a, c, e and o all collapse into the same blob — so the small size is drawn
 * separately with the features that survive at four rows of x-height.
 *
 * LARGE — 12 sub-rows, strokes two pixels thick:
 *   rows 0..1    ascender-only zone (b d f h i j k l t and digits)
 *   rows 2..9    x-height body (8 rows — exactly four terminal cells)
 *   rows 10..11  descender (g j p q y and comma)
 *
 * SMALL — 6 sub-rows, strokes still two pixels wide horizontally:
 *   row 0        ascender
 *   rows 1..4    x-height body
 *   row 5        descender
 *
 * `#` = ink, `.` = empty.
 */

export const LARGE_H = 12;
export const SMALL_H = 6;

export type Glyph = {
  readonly width: number;
  readonly rows: readonly string[];
};

function build(height: number, rows: string[]): Glyph {
  if (rows.length !== height) {
    throw new Error(`Glyph needs ${height} rows, got ${rows.length}`);
  }
  const width = rows[0].length;
  for (const row of rows) {
    if (row.length !== width) {
      throw new Error(`Glyph rows must all be ${width} wide, got "${row}"`);
    }
  }
  return { width, rows };
}

/** Large-atlas glyph (12 sub-rows). */
function G(...rows: string[]): Glyph {
  return build(LARGE_H, rows);
}

/** Small-atlas glyph (6 sub-rows). */
function S(...rows: string[]): Glyph {
  return build(SMALL_H, rows);
}

