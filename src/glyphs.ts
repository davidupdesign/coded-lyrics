/** One rung of the size ladder the renderer walks to fit a block. */
export interface FontScale {
  /** Which atlas to draw from. */
  readonly subRows: number;
  /** Horizontal squeeze, 1 = as drawn. Vertical detail is untouched. */
  readonly condense: number;
}

/**
 * Sizes to try, largest first.
 *
 * The condensed rung squeezes width only — merging columns costs far less
 * legibility than merging rows, so it buys a step between the two atlases
 * without a third set of hand-drawn glyphs.
 */
export const SCALE_LADDER: readonly FontScale[] = [
  { subRows: LARGE_H, condense: 1 },
  { subRows: LARGE_H, condense: 0.72 },
  { subRows: SMALL_H, condense: 1 },
  { subRows: SMALL_H, condense: 0.75 },
];

const FALLBACK = LARGE["?"];

function atlasFor(subRows: number): Record<string, Glyph> {
  return subRows === SMALL_H ? SMALL : LARGE;
}

const condenseCache = new Map<string, Glyph>();

/**
 * Squeeze a glyph horizontally by `factor`.
 *
 * Uses max-pooling — a target column is ink if *any* source column mapping to
 * it is ink — so two-pixel stems survive instead of dropping out.
 */
function condenseGlyph(glyph: Glyph, key: string, factor: number): Glyph {
  const width = Math.max(1, Math.round(glyph.width * factor));
  if (width === glyph.width) return glyph;

  const cacheKey = `${key}|${factor}`;
  const hit = condenseCache.get(cacheKey);
  if (hit) return hit;

  const rows = glyph.rows.map((row) => {
    let out = "";
    for (let x = 0; x < width; x++) {
      const x0 = Math.floor((x * glyph.width) / width);
      const x1 = Math.max(x0 + 1, Math.floor(((x + 1) * glyph.width) / width));
      let ink = false;
      for (let sx = x0; sx < x1; sx++) {
        if (row[sx] === "#") {
          ink = true;
          break;
        }
      }
      out += ink ? "#" : ".";
    }
    return out;
  });

  const condensed: Glyph = { width, rows };
  condenseCache.set(cacheKey, condensed);
  return condensed;
}

/** Glyph for a character at a given size. */
export function glyphAt(ch: string, scale: FontScale): Glyph {
  const key = ch.toLowerCase();
  const glyph = atlasFor(scale.subRows)[key] ?? FALLBACK;
  return scale.condense === 1
    ? glyph
    : condenseGlyph(glyph, `${scale.subRows}:${key}`, scale.condense);
}
